SIZE_IOU_BINS = (0.0, 0.25, 0.5, 0.75, 0.8, 0.9, 1.0)
BOX_COLLISION_EPS_CM = 1e-6
DIRECTION_METADATA_SCHEMA_VERSION = "lc_bgplacenet_stage2_direction_metadata/v1"
DIRECTION_RELATIONS = (
    "the front right of",
    "the front left of",
    "the back right of",
    "the back left of",
    "the right of",
    "in front of",
    "the left of",
    "the top of",
    "behind",
    "below",
)


def parse_args() -> argparse.Namespace:
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description="Benchmark LC-BGPlaceNet Stage 2 predictions.")
    parser.add_argument("--config", type=Path, default=PROJECT_ROOT / "configs/lc_bgplacenet_stage2.yaml")
    parser.add_argument(
        "--predictions",
        type=Path,
        default=PROJECT_ROOT / "outputs/lc_bgplacenet_stage2/inference_stage2_test/predictions.json",
        help="Stage 2 predictions.json generated by tools/infer_lc_bgplacenet_stage2.py.",
    )
    parser.add_argument("--split", choices=("train", "valid", "val", "test"), default="test")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=PROJECT_ROOT / "outputs/lc_bgplacenet_stage2/benchmark_stage2_test",
    )
    parser.add_argument(
        "--direction-metadata",
        type=Path,
        default=PROJECT_ROOT / "outputs/lc_bgplacenet_stage2/direction_metadata_test.json",
        help="Metadata generated by tools/generate_lc_bgplacenet_stage2_direction_metadata.py.",
    )
    parser.add_argument("--size-iou-threshold", type=float, default=0.8)
    return parser.parse_args()


def _resolve_project_path(path_like: str | os.PathLike[str]) -> Path:
    """Resolve config paths relative to the project root."""
    path = Path(path_like)
    return path if path.is_absolute() else PROJECT_ROOT / path


def resolve_config_paths(cfg: dict[str, Any]) -> dict[str, Any]:
    """Return a copy of cfg with data paths resolved against PROJECT_ROOT."""
    resolved = copy.deepcopy(cfg)
    data_cfg = resolved.get("data", {})
    if data_cfg.get("split_dir") is not None:
        data_cfg["split_dir"] = os.fspath(_resolve_project_path(data_cfg["split_dir"]))
    for source in data_cfg.get("sources", []):
        for key in ("dataset_dir", "free_bbox_dir", "labels_path"):
            if source.get(key) is not None:
                source[key] = os.fspath(_resolve_project_path(source[key]))
    return resolved


def load_predictions(path: Path) -> list[dict[str, Any]]:
    """Load predictions and fail with the matching inference command when missing."""
    if not path.exists():
        raise FileNotFoundError(
            f"Predictions file not found: {path}\n"
            "Run inference first, for example:\n"
            "  python tools/infer_lc_bgplacenet_stage2.py "
            "--config configs/lc_bgplacenet_stage2.yaml "
            "--checkpoint outputs/lc_bgplacenet_stage2/best.pt "
            "--split test"
        )
    with path.open("r", encoding="utf-8") as f:
        rows = json.load(f)
    if not isinstance(rows, list):
        raise ValueError(f"Predictions file must contain a list: {path}")
    return rows


def load_direction_metadata(path: Path) -> dict[str, dict[str, Any]]:
    """Load item_id keyed language direction metadata."""
    if not path.exists():
        raise FileNotFoundError(
            f"Direction metadata file not found: {path}\n"
            "Generate it first, for example:\n"
            "  python tools/generate_lc_bgplacenet_stage2_direction_metadata.py "
            "--config configs/lc_bgplacenet_stage2.yaml "
            "--split test "
            "--output outputs/lc_bgplacenet_stage2/direction_metadata_test.json"
        )
    with path.open("r", encoding="utf-8") as f:
        payload = json.load(f)
    if payload.get("schema_version") != DIRECTION_METADATA_SCHEMA_VERSION:
        raise ValueError(f"Unsupported direction metadata schema_version in {path}: {payload.get('schema_version')}")
    items = payload.get("items", [])
    if not isinstance(items, list):
        raise ValueError(f"Direction metadata items must be a list: {path}")
    return {str(item["item_id"]): item for item in items}


def parse_target_direction(instruction: str) -> tuple[str, str]:
    """Parse the target relation and reference name from the auto-label instruction text."""
    match = re.search(r"\bto\s+(.+?)\.\s*$", str(instruction).strip())
    if match is None:
        raise ValueError(f"Cannot parse target direction from instruction: {instruction}")
    target_phrase = match.group(1).strip()
    for relation in DIRECTION_RELATIONS:
        prefix = f"{relation} "
        if target_phrase == relation:
            raise ValueError(f"Missing reference name in instruction: {instruction}")
        if target_phrase.startswith(prefix):
            return relation, target_phrase[len(prefix) :].strip()
    raise ValueError(f"Unknown target relation in instruction: {instruction}")


def compute_size_iou(pred_dims: np.ndarray, gt_dims: np.ndarray) -> float:
    """Compute dimension-only volume IoU with w/h/l kept in corresponding order."""
    pred = np.maximum(np.asarray(pred_dims, dtype=np.float64), 0.0)
    gt = np.maximum(np.asarray(gt_dims, dtype=np.float64), 0.0)
    intersection = float(np.prod(np.minimum(pred, gt)))
    union = float(np.prod(np.maximum(pred, gt)))
    if union <= 0.0:
        return 0.0
    return intersection / union


def compute_size_metrics(
    place_box: np.ndarray,
    place_box_gt: np.ndarray,
    threshold: float,
) -> dict[str, Any]:
    """Compute size IoU and pass/fail for one prediction."""
    size_iou = compute_size_iou(place_box[3:6], place_box_gt[3:6])
    return {
        "size_iou": float(size_iou),
        "size_correct": bool(size_iou >= float(threshold)),
    }


def place_box_to_corners(place_box: np.ndarray) -> np.ndarray:
    """Convert (x, y, z, dx, dy, dz, yaw) to 8 world corners."""
    bbox, transform = _place_box_to_bbox_and_transform(place_box)
    return transform_points(get_bbox_corners(bbox), transform)


def object_corners_world(obj: ObjectInfo) -> np.ndarray:
    """Return world corners for one canonical scene object."""
    return transform_points(get_bbox_corners(obj.bbox3d_canonical), obj.pose_world)


def load_direction_scene_context(item: Stage2IndexItem) -> dict[str, Any]:
    """Read camera and object geometry needed by auto-label direction checks."""
    record = load_sample_record(item.dataset_dir / "samples" / f"{item.sample_id}.json")
    camera_record = record["camera"]
    camera = CameraParams(
        fx=float(camera_record["fx"]),
        fy=float(camera_record["fy"]),
        cx=float(camera_record["cx"]),
        cy=float(camera_record["cy"]),
        E_c2w=np.asarray(camera_record["E_c2w"], dtype=np.float64),
        img_w=int(camera_record["img_w"]),
        img_h=int(camera_record["img_h"]),
    )
    objects = [
        ObjectInfo(
            obj_id=str(obj["obj_id"]),
            class_name=str(obj["class_name"]),
            bbox3d_canonical=np.asarray(obj["bbox3d_canonical"], dtype=np.float64),
            pose_world=np.asarray(obj["pose_world"], dtype=np.float64),
        )
        for obj in record["objects"]
    ]
    return {"camera": camera, "object_by_id": {str(obj.obj_id): obj for obj in objects}}


def compute_direction_metrics(
    place_box: np.ndarray,
    direction_metadata: dict[str, Any],
    scene_context: dict[str, Any],
) -> dict[str, Any]:
    """Check whether the predicted box satisfies the language target direction."""
    ref_id = str(direction_metadata["reference_object_id"])
    ref_obj = scene_context["object_by_id"].get(ref_id)
    if ref_obj is None:
        return {
            "direction_hit": False,
            "target_relation": str(direction_metadata["target_relation"]),
            "predicted_relation": None,
            "reference_object_id": ref_id,
            "reference_name": str(direction_metadata.get("reference_name", "")),
        }

    camera = scene_context["camera"]
    target_relation = str(direction_metadata["target_relation"])
    predicted_relation = describe_spatial_relation(
        place_box_to_corners(place_box),
        object_corners_world(ref_obj),
        camera.E_w2c,
        camera.K,
    )
    return {
        "direction_hit": bool(predicted_relation == target_relation),
        "target_relation": target_relation,
        "predicted_relation": predicted_relation,
        "reference_object_id": ref_id,
        "reference_name": str(direction_metadata.get("reference_name", "")),
    }


def _place_box_to_bbox_and_transform(place_box: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Convert (x, y, z, dx, dy, dz, yaw) to a centered local AABB and world transform."""
    box = np.asarray(place_box, dtype=np.float64)
    dims = np.maximum(box[3:6], 1e-4)
    yaw = float(box[6])
    c, s = math.cos(yaw), math.sin(yaw)
    transform = np.eye(4, dtype=np.float64)
    transform[:3, :3] = np.array(
        [
            [c, -s, 0.0],
            [s, c, 0.0],
            [0.0, 0.0, 1.0],
        ],
        dtype=np.float64,
    )
    transform[:3, 3] = box[:3]
    bbox = np.concatenate([-dims * 0.5, dims * 0.5])
    return bbox, transform


def build_collision_context(scene_objects: list[dict[str, Any]]) -> dict[str, Any]:
    """Build reusable scene object OBBs for box-box collision checks."""
    object_obbs = [
        _obb_from_bbox_transform(
            str(obj.get("object_id", index)),
            np.asarray(obj["canonical_aabb_object"], dtype=np.float64),
            np.asarray(obj["original_pose_world"], dtype=np.float64),
        )
        for index, obj in enumerate(scene_objects)
    ]
    return {"object_obbs": object_obbs}


def compute_collision_metrics(place_box: np.ndarray, context: dict[str, Any]) -> dict[str, Any]:
    """Check whether one predicted yaw-only box intersects any scene object OBB."""
    bbox, transform = _place_box_to_bbox_and_transform(place_box)
    pred_obb = _obb_from_bbox_transform("prediction", bbox, transform)
    colliding_ids = [
        str(obj["object_id"])
        for obj in context["object_obbs"]
        if _obb_intersects(pred_obb, obj, eps=BOX_COLLISION_EPS_CM)
    ]
    return {
        "collision": bool(colliding_ids),
        "collision_object_count": int(len(colliding_ids)),
        "collision_object_ids": colliding_ids,
    }


def _obb_from_bbox_transform(object_id: str, bbox3d: np.ndarray, transform: np.ndarray) -> dict[str, Any]:
    """Convert a local AABB and object-to-world transform to an OBB record."""
    bbox = np.asarray(bbox3d, dtype=np.float64)
    pose = np.asarray(transform, dtype=np.float64)
    local_center = (bbox[:3] + bbox[3:]) * 0.5
    center = pose[:3, :3] @ local_center + pose[:3, 3]
    half_extents = np.maximum((bbox[3:] - bbox[:3]) * 0.5, 1e-4)

    axes = pose[:3, :3]
    axis_scales = np.linalg.norm(axes, axis=0)
    if np.any(axis_scales < 1e-12):
        raise ValueError(f"Object {object_id} has a degenerate OBB transform")
    axes = axes / axis_scales[None, :]
    return {
        "object_id": object_id,
        "center": center.astype(np.float64),
        "axes": axes.astype(np.float64),
        "half_extents": (half_extents * axis_scales).astype(np.float64),
    }


def _obb_intersects(a: dict[str, Any], b: dict[str, Any], eps: float = BOX_COLLISION_EPS_CM) -> bool:
    """Return True only when two OBBs have positive volume overlap."""
    a_axes = np.asarray(a["axes"], dtype=np.float64)
    b_axes = np.asarray(b["axes"], dtype=np.float64)
    cross_axes = np.cross(a_axes.T[:, None, :], b_axes.T[None, :, :]).reshape(-1, 3)
    candidate_axes = np.vstack([a_axes.T, b_axes.T, cross_axes])
    axis_norms = np.linalg.norm(candidate_axes, axis=1)
    candidate_axes = candidate_axes[axis_norms > 1e-8]
    candidate_axes /= np.linalg.norm(candidate_axes, axis=1, keepdims=True)

    center_delta = np.asarray(b["center"], dtype=np.float64) - np.asarray(a["center"], dtype=np.float64)
    center_distances = np.abs(candidate_axes @ center_delta)
    radius_a = np.abs(candidate_axes @ a_axes) @ np.asarray(a["half_extents"], dtype=np.float64)
    radius_b = np.abs(candidate_axes @ b_axes) @ np.asarray(b["half_extents"], dtype=np.float64)
    return bool(np.all(center_distances < radius_a + radius_b - float(eps)))


def _build_item_lookup(cfg: dict[str, Any], split: str) -> dict[str, Stage2IndexItem]:
    """Build Stage 2 metadata for the requested fixed split."""
    sources = build_sources_from_config(cfg)
    items = build_stage2_index(sources)
    split_items = select_stage2_split_items(items, cfg["data"]["split_dir"], normalize_stage1_split(split))
    return {item.item_id: item for item in split_items}


def _get_collision_context(
    item: Stage2IndexItem,
    cache: dict[tuple[str, str], dict[str, Any]],
) -> dict[str, Any]:
    """Load and cache one scene collision context."""
    key = (item.source_name, item.sample_id)
    if key not in cache:
        placement_path = item.free_bbox_dir / "placements" / f"{item.sample_id}__placements.json"
        with placement_path.open("r", encoding="utf-8") as f:
            payload = json.load(f)
        cache[key] = build_collision_context(payload.get("objects", []))
    return cache[key]


def _distribution(values: np.ndarray) -> dict[str, int]:
    """Count values in fixed size-IoU bins."""
    if len(values) == 0:
        return {f"[{SIZE_IOU_BINS[i]:.2f},{SIZE_IOU_BINS[i + 1]:.2f}{')' if i + 1 < len(SIZE_IOU_BINS) - 1 else ']'}": 0 for i in range(len(SIZE_IOU_BINS) - 1)}
    clipped = np.clip(values, SIZE_IOU_BINS[0], SIZE_IOU_BINS[-1])
    counts = np.histogram(clipped, bins=np.asarray(SIZE_IOU_BINS, dtype=np.float64))[0]
    return {
        f"[{SIZE_IOU_BINS[i]:.2f},{SIZE_IOU_BINS[i + 1]:.2f}{')' if i + 1 < len(SIZE_IOU_BINS) - 1 else ']'}": int(counts[i])
        for i in range(len(counts))
    }


def summarize_rows(rows: list[dict[str, Any]]) -> dict[str, Any]:
    """Summarize per-sample benchmark rows."""
    if not rows:
        return {
            "sample_count": 0,
            "size_accuracy": 0.0,
            "size_iou": {},
            "size_iou_distribution": _distribution(np.asarray([], dtype=np.float64)),
            "direction_hit_rate": 0.0,
            "collision_rate": 0.0,
            "collision_object_count_mean": 0.0,
        }

    size_values = np.asarray([row["size_iou"] for row in rows], dtype=np.float64)
    direction_hits = np.asarray([row["direction_hit"] for row in rows], dtype=bool)
    collisions = np.asarray([row["collision"] for row in rows], dtype=bool)
    collision_counts = np.asarray([row["collision_object_count"] for row in rows], dtype=np.float64)
    return {
        "sample_count": int(len(rows)),
        "size_accuracy": float(np.mean([row["size_correct"] for row in rows])),
        "size_iou": {
            "mean": float(size_values.mean()),
            "median": float(np.median(size_values)),
            "p10": float(np.percentile(size_values, 10)),
            "p25": float(np.percentile(size_values, 25)),
            "p75": float(np.percentile(size_values, 75)),
            "p90": float(np.percentile(size_values, 90)),
        },
        "size_iou_distribution": _distribution(size_values),
        "direction_hit_rate": float(direction_hits.mean()),
        "collision_rate": float(collisions.mean()),
        "collision_object_count_mean": float(collision_counts.mean()),
    }


def _json_default(value: Any) -> Any:
    """JSON serializer for numpy scalars and non-finite floats."""
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.floating):
        return None if not math.isfinite(float(value)) else float(value)
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, Path):
        return os.fspath(value)
    raise TypeError(f"Object of type {type(value)} is not JSON serializable")


def run_benchmark(
    cfg: dict[str, Any],
    predictions: list[dict[str, Any]],
    direction_metadata: dict[str, dict[str, Any]],
    split: str,
    size_iou_threshold: float,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Compute all benchmark metrics for loaded predictions."""
    item_by_id = _build_item_lookup(cfg, split)
    prediction_ids = {str(row.get("item_id")) for row in predictions}
    split_ids = set(item_by_id)
    unknown_ids = sorted(prediction_ids - split_ids)
    missing_ids = sorted(split_ids - prediction_ids)
    if unknown_ids:
        preview = ", ".join(unknown_ids[:5])
        raise ValueError(f"{len(unknown_ids)} prediction item_ids are not in split={split}: {preview}")
    if missing_ids:
        preview = ", ".join(missing_ids[:5])
        raise ValueError(f"{len(missing_ids)} split={split} item_ids are missing predictions: {preview}")
    missing_direction_ids = sorted(prediction_ids - set(direction_metadata))
    if missing_direction_ids:
        preview = ", ".join(missing_direction_ids[:5])
        raise ValueError(f"{len(missing_direction_ids)} prediction item_ids are missing direction metadata: {preview}")

    voxel_size_cm = float(cfg["data"]["voxel_size_cm"])
    collision_cache: dict[tuple[str, str], dict[str, Any]] = {}
    direction_scene_cache: dict[tuple[str, str], dict[str, Any]] = {}
    per_sample_rows = []

    for row in predictions:
        item = item_by_id[str(row["item_id"])]
        place_box = np.asarray(row["place_box"], dtype=np.float64)
        place_box_gt = np.asarray(row["place_box_gt"], dtype=np.float64)
        collision_context = _get_collision_context(item, collision_cache)
        scene_key = (item.source_name, item.sample_id)
        if scene_key not in direction_scene_cache:
            direction_scene_cache[scene_key] = load_direction_scene_context(item)

        metrics = {
            **compute_size_metrics(place_box, place_box_gt, size_iou_threshold),
            **compute_direction_metrics(
                place_box,
                direction_metadata[str(row["item_id"])],
                direction_scene_cache[scene_key],
            ),
            **compute_collision_metrics(place_box, collision_context),
        }
        per_sample_rows.append(
            {
                "item_id": item.item_id,
                "source_name": item.source_name,
                "sample_id": item.sample_id,
                "object_id": item.object_id,
                "cluster_id": int(item.cluster_id),
                **metrics,
            }
        )

    by_source = {
        source_name: summarize_rows([row for row in per_sample_rows if row["source_name"] == source_name])
        for source_name in sorted({row["source_name"] for row in per_sample_rows})
    }
    summary = {
        "split": normalize_stage1_split(split),
        "parameters": {
            "size_iou_threshold": float(size_iou_threshold),
            "voxel_size_cm": voxel_size_cm,
            "direction_metric": "auto_label_spatial_relation",
        },
        "overall": summarize_rows(per_sample_rows),
        "by_source": by_source,
    }
    return per_sample_rows, summary


def save_outputs(output_dir: Path, per_sample_rows: list[dict[str, Any]], summary: dict[str, Any]) -> None:
    """Write benchmark JSON and JSONL outputs."""
    output_dir.mkdir(parents=True, exist_ok=True)
    with (output_dir / "per_sample_metrics.jsonl").open("w", encoding="utf-8") as f:
        for row in per_sample_rows:
            f.write(json.dumps(row, ensure_ascii=False, default=_json_default) + "\n")
    with (output_dir / "benchmark_metrics.json").open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False, default=_json_default)


def main() -> None:
    """Run the benchmark CLI."""
    args = parse_args()
    cfg = resolve_config_paths(load_config(args.config))
    predictions = load_predictions(args.predictions)
    direction_metadata = load_direction_metadata(args.direction_metadata)
    per_sample_rows, summary = run_benchmark(
        cfg,
        predictions,
        direction_metadata=direction_metadata,
        split=args.split,
        size_iou_threshold=float(args.size_iou_threshold),
    )
    save_outputs(args.output_dir, per_sample_rows, summary)

    overall = summary["overall"]
    print(f"Wrote Stage 2 benchmark outputs to {args.output_dir}")
    print(f"Samples: {overall['sample_count']}")
    print(f"Size accuracy: {overall['size_accuracy']:.4f}")
    print(f"Size IoU mean/median: {overall['size_iou']['mean']:.4f}/{overall['size_iou']['median']:.4f}")
    print(f"Direction hit rate: {overall['direction_hit_rate']:.4f}")
    print(f"Collision rate: {overall['collision_rate']:.4f}")


if __name__ == "__main__":
    main()
